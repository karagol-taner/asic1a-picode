#!/usr/bin/env python3
"""
export_ladder_definition.py - write the ladder and burial constants into data/.

    python3 codes/export_ladder_definition.py          # write or refresh
    python3 codes/export_ladder_definition.py --check  # fail on any difference

Sources them from the pI-code method folder, so it runs only on a machine that
has it; with the folder absent the script exits non-zero rather than writing a
snapshot it cannot source. --check re-reads that folder and exits non-zero if
the committed snapshot does not match.

The snapshot holds the ladder edges of Figure 1, the per-residue charges of
Table 2, the accessibility cutoffs and salt-bridge distance of the Methods, and
the maximum-accessibility table of Tien et al. (2013).
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import picode_paths as P

LADDER = P.project('data', 'ladder_definition.json')
BURIAL = P.project('data', 'burial_thresholds.json')

NOTE_L = ('ladder edges and residue charges; published in Figure 1 and Table 2 '
          'of the manuscript. Generated by codes/export_ladder_definition.py '
          'from the ladder edge-cost script, which is not part of this '
          'repository.')
NOTE_B = ('relative-accessibility cutoffs, salt-bridge distance and the '
          'maximum-accessibility table of Tien et al. (2013) PLoS ONE 8:e80635. '
          'Generated by codes/export_ladder_definition.py from the burial '
          'script, which is not part of this repository.')


def collect():
    L = P.load_ladder(allow_snapshot=False)
    lpo = P.load_lpo(allow_snapshot=False)
    ladder = {'_note': NOTE_L,
              'core': [list(e) for e in L.CORE],
              'arg': [list(e) for e in L.ARG],
              'ext': [list(e) for e in L.EXT],
              'basicdir': [list(e) for e in sorted(L.BASICDIR)],
              'charge': dict(L.CHARGE)}
    burial = {'_note': NOTE_B,
              'buried_rsa': float(lpo.BURIED_RSA),
              'partial_rsa': float(lpo.PARTIAL_RSA),
              'salt_bridge': float(lpo.SALT_BRIDGE),
              'maxasa': dict(lpo.MAXASA)}
    return ladder, burial


def main():
    check = '--check' in sys.argv[1:]
    bad = [a for a in sys.argv[1:] if a != '--check']
    if bad:
        sys.exit('FATAL: unknown argument %s; use --check or no argument' % bad[0])

    ladder, burial = collect()
    rc = 0
    for path, obj in ((LADDER, ladder), (BURIAL, burial)):
        txt = json.dumps(obj, indent=2, sort_keys=True) + '\n'
        name = os.path.relpath(path, P.project())
        if check:
            if not os.path.exists(path):
                print('MISSING  %s' % name)
                rc = 1
            elif open(path).read() != txt:
                print('DRIFTED  %s no longer matches the method folder' % name)
                rc = 1
            else:
                print('ok       %s' % name)
        else:
            old = open(path).read() if os.path.exists(path) else None
            with open(path, 'w') as fh:
                fh.write(txt)
            print('%-8s %s' % ('same' if old == txt else 'written', name))
    if check and rc:
        sys.exit('FATAL: committed snapshot does not match the method folder; '
                 'rerun without --check to refresh it')
    return rc


if __name__ == '__main__':
    sys.exit(main())
